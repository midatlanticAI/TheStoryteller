// Packs the built web app (apps/web/dist) into a TypeScript module so the
// compiled executable carries the whole game inside one file.
import { readFileSync, readdirSync, statSync, writeFileSync, existsSync } from "node:fs";
import { join, relative, extname } from "node:path";
import { fileURLToPath } from "node:url";

const here = fileURLToPath(new URL(".", import.meta.url));
const dist = join(here, "../../web/dist");
if (!existsSync(join(dist, "index.html"))) {
  if (process.argv.includes("--allow-empty")) {
    writeFileSync(join(here, "../src/assets.generated.ts"), "// Placeholder: build apps/web and run scripts/embed-assets.mjs.\nexport const ASSETS: Record<string, { type: string; body: string }> = {};\n");
    console.warn("apps/web/dist is missing: wrote an empty asset table for type-checking.");
    process.exit(0);
  }
  console.error("apps/web/dist is missing: run `pnpm --filter @storyteller/web build` first.");
  process.exit(1);
}
const TYPES = {
  ".html": "text/html; charset=utf-8",
  ".js": "text/javascript; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".svg": "image/svg+xml",
  ".json": "application/json",
  ".webmanifest": "application/manifest+json",
  ".png": "image/png",
  ".ico": "image/x-icon",
  ".txt": "text/plain; charset=utf-8",
};
const files = [];
const walk = (dir) => {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) walk(full);
    else files.push(full);
  }
};
walk(dist);
const entries = files
  .filter((f) => !/(^|\/)(sw\.js|workbox-[^/]+\.js|registerSW\.js)$/.test(relative(dist, f)))
  .map((f) => {
    const path = "/" + relative(dist, f).split("\\").join("/");
    const type = TYPES[extname(f)] ?? "application/octet-stream";
    return `  ${JSON.stringify(path)}: { type: ${JSON.stringify(type)}, body: ${JSON.stringify(readFileSync(f).toString("base64"))} },`;
  });
writeFileSync(
  join(here, "../src/assets.generated.ts"),
  `// Generated by scripts/embed-assets.mjs from apps/web/dist. Do not edit.\nexport const ASSETS: Record<string, { type: string; body: string }> = {\n${entries.join("\n")}\n};\n`,
);
console.log(`Embedded ${entries.length} files from apps/web/dist.`);
